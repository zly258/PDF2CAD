"""标准 DXF 写入器：GBK/ANSI_936 编码 + txt.shx/gbcbig.shx 国标字库绑定与线段去重（参考脚本 §9）。"""
import numpy as np

from .encoding import format_cad_text
from ..version import __version__, __copyright__


def deduplicate_line_pairs(seg_list):
    """消除尺寸块内完全重合的冗余线段。"""
    seen = set()
    out = []
    for p0, p1 in seg_list:
        k1 = (round(p0[0], 2), round(p0[1], 2), round(p1[0], 2), round(p1[1], 2))
        k2 = (round(p1[0], 2), round(p1[1], 2), round(p0[0], 2), round(p0[1], 2))
        if k1 not in seen and k2 not in seen:
            seen.add(k1)
            out.append((p0, p1))
    return out


def write_standard_dxf(
    out_dxf_path, all_layers, lines_out, circles_out, arcs_out, polylines_out,
    solids_out, texts_out, dimensions_out=None, sym_blocks_out=None
):
    dimensions_out = dimensions_out or []
    sym_blocks_out = sym_blocks_out or []

    dim_txt_h = float(np.median([d['text_height'] for d in dimensions_out])) if dimensions_out else 3.5
    dim_arrow_sz = float(np.median([d['arrow_len'] for d in dimensions_out])) if dimensions_out else 2.5

    # 严格使用 GBK (ANSI_936) 编码写入，且所有生僻字符已由 format_cad_text 转为 GB2312 或 \U+XXXX
    with open(out_dxf_path, 'w', encoding='gbk', errors='replace') as f:
        def wp(code, val):
            f.write(f"{code:3d}\n{val}\n")

        wp(999, f"Generated by pdf2cad_pro.py v{__version__} | {__copyright__}")
        wp(0, "SECTION")
        wp(2, "HEADER")
        wp(9, "$ACADVER")
        wp(1, "AC1009")
        wp(9, "$DWGCODEPAGE")
        wp(3, "ANSI_936")
        wp(9, "$INSUNITS")
        wp(70, 4)
        all_x_ext = [p[0] for _, _, p0, p1 in lines_out for p in (p0, p1)] + [cx for _, _, cx, _, _ in circles_out] + [p[0] for _, _, pts, _ in polylines_out for p in pts]
        all_y_ext = [p[1] for _, _, p0, p1 in lines_out for p in (p0, p1)] + [cy for _, _, _, cy, _ in circles_out] + [p[1] for _, _, pts, _ in polylines_out for p in pts]
        ext_min_x, ext_max_x = (min(all_x_ext), max(all_x_ext)) if all_x_ext else (0.0, 841.0)
        ext_min_y, ext_max_y = (min(all_y_ext), max(all_y_ext)) if all_y_ext else (0.0, 594.0)
        wp(9, "$EXTMIN")
        wp(10, f"{ext_min_x:.4f}")
        wp(20, f"{ext_min_y:.4f}")
        wp(30, "0.0")
        wp(9, "$EXTMAX")
        wp(10, f"{ext_max_x:.4f}")
        wp(20, f"{ext_max_y:.4f}")
        wp(30, "0.0")
        wp(9, "$DIMTXT")
        wp(40, f"{dim_txt_h:.4f}")
        wp(9, "$DIMASZ")
        wp(40, f"{dim_arrow_sz:.4f}")
        wp(9, "$DIMEXE")
        wp(40, f"{dim_arrow_sz * 0.5:.4f}")
        wp(9, "$DIMEXO")
        wp(40, "0.0")
        wp(9, "$DIMGAP")
        wp(40, f"{dim_txt_h * 0.25:.4f}")
        wp(9, "$DIMTIH")
        wp(70, 0)
        wp(9, "$DIMTOH")
        wp(70, 0)
        wp(9, "$DIMTAD")
        wp(70, 1)
        wp(9, "$DIMDEC")
        wp(70, 0)
        wp(0, "ENDSEC")

        wp(0, "SECTION")
        wp(2, "TABLES")

        wp(0, "TABLE")
        wp(2, "LTYPE")
        wp(70, 3)

        wp(0, "LTYPE")
        wp(2, "CONTINUOUS")
        wp(70, 0)
        wp(3, "Solid line")
        wp(72, 65)
        wp(73, 0)
        wp(40, "0.0")

        wp(0, "LTYPE")
        wp(2, "CENTER")
        wp(70, 0)
        wp(3, "Center ____ _ ____ _ ____ _ ____")
        wp(72, 65)
        wp(73, 4)
        wp(40, "50.0")
        wp(49, "30.0")
        wp(49, "-5.0")
        wp(49, "10.0")
        wp(49, "-5.0")

        wp(0, "LTYPE")
        wp(2, "DASHED")
        wp(70, 0)
        wp(3, "Dashed __ __ __ __ __")
        wp(72, 65)
        wp(73, 2)
        wp(40, "15.0")
        wp(49, "10.0")
        wp(49, "-5.0")
        wp(0, "ENDTAB")

        # 绑定 CAD 原生内置 txt.shx + gbcbig.shx 国标中文大字体，采用 0.78 工程字宽比，杜绝 ???? 乱码与表格文字溢出
        wp(0, "TABLE")
        wp(2, "STYLE")
        wp(70, 1)
        wp(0, "STYLE")
        wp(2, "STANDARD")
        wp(70, 0)
        wp(40, "0.0")
        wp(41, "0.78")
        wp(50, "0.0")
        wp(71, 0)
        wp(42, f"{dim_txt_h:.4f}")
        wp(3, "txt.shx")
        wp(4, "gbcbig.shx")
        wp(0, "ENDTAB")

        wp(0, "TABLE")
        wp(2, "LAYER")
        wp(70, len(all_layers))
        for lname in all_layers:
            safe_lname = format_cad_text(lname, for_layer_or_block=True)
            wp(0, "LAYER")
            wp(2, safe_lname)
            wp(70, 0)
            l_upper = lname.upper()
            l_color = 1 if ("CENTER" in l_upper or "中心" in l_upper) else (3 if ("DIM" in l_upper or "标注" in l_upper) else (6 if ("DASH" in l_upper or "虚线" in l_upper) else 7))
            l_type = "CENTER" if ("CENTER" in l_upper or "中心" in l_upper) else ("DASHED" if ("HIDE" in l_upper or "DASH" in l_upper or "虚线" in l_upper) else "CONTINUOUS")
            wp(62, l_color)
            wp(6, l_type)
        wp(0, "ENDTAB")
        wp(0, "ENDSEC")

        wp(0, "SECTION")
        wp(2, "BLOCKS")
        for d in dimensions_out:
            wp(0, "BLOCK")
            wp(8, "0")
            wp(2, d['block_name'])
            wp(70, 1)
            wp(10, "0.0")
            wp(20, "0.0")
            wp(30, "0.0")

            lay = format_cad_text(d['layer'], for_layer_or_block=True)
            aci = d['aci']
            for p0, p1 in deduplicate_line_pairs(d['dim_lines'] + d['ext_lines']):
                wp(0, "LINE")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{p0[0]:.4f}")
                wp(20, f"{p0[1]:.4f}")
                wp(30, "0.0")
                wp(11, f"{p1[0]:.4f}")
                wp(21, f"{p1[1]:.4f}")
                wp(31, "0.0")

            for cx, cy, r, a0, a1_ang in d.get('arcs', []):
                wp(0, "ARC")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{cx:.4f}")
                wp(20, f"{cy:.4f}")
                wp(30, "0.0")
                wp(40, f"{r:.4f}")
                wp(50, f"{a0:.4f}")
                wp(51, f"{a1_ang:.4f}")

            for apts in (d['arrow1_pts'], d['arrow2_pts']):
                p0, p1, p2 = apts[0], apts[1], apts[2]
                if len(apts) >= 4:
                    p2, p3 = apts[3], apts[2]
                else:
                    p3 = p2
                wp(0, "SOLID")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{p0[0]:.4f}")
                wp(20, f"{p0[1]:.4f}")
                wp(30, "0.0")
                wp(11, f"{p1[0]:.4f}")
                wp(21, f"{p1[1]:.4f}")
                wp(31, "0.0")
                wp(12, f"{p2[0]:.4f}")
                wp(22, f"{p2[1]:.4f}")
                wp(32, "0.0")
                wp(13, f"{p3[0]:.4f}")
                wp(23, f"{p3[1]:.4f}")
                wp(33, "0.0")

            if d['text']:
                wp(0, "TEXT")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{d['text_ins'][0]:.4f}")
                wp(20, f"{d['text_ins'][1]:.4f}")
                wp(30, "0.0")
                wp(40, f"{d['text_height']:.4f}")
                wp(41, "0.78")
                wp(1, format_cad_text(d['text']))
                wp(50, f"{d['angle_deg']:.2f}")
                wp(7, "STANDARD")

            for et_txt, et_pos, et_h, et_ang in d.get('extra_texts', []):
                wp(0, "TEXT")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{et_pos[0]:.4f}")
                wp(20, f"{et_pos[1]:.4f}")
                wp(30, "0.0")
                wp(40, f"{et_h:.4f}")
                wp(41, "0.78")
                wp(1, format_cad_text(et_txt))
                wp(50, f"{et_ang:.2f}")
                wp(7, "STANDARD")

            wp(0, "ENDBLK")
            wp(8, "0")

        written_sym_block_names = set()
        for sb in sym_blocks_out:
            if sb['block_name'] in written_sym_block_names:
                continue
            written_sym_block_names.add(sb['block_name'])
            wp(0, "BLOCK")
            wp(8, "0")
            wp(2, sb['block_name'])
            wp(70, 0)
            wp(10, "0.0")
            wp(20, "0.0")
            wp(30, "0.0")

            for p_lay, p_aci, pts, is_closed in sb.get('polylines', []):
                safe_play = format_cad_text(p_lay, for_layer_or_block=True)
                wp(0, "POLYLINE")
                wp(8, safe_play)
                wp(62, p_aci)
                wp(66, 1)
                wp(10, "0.0")
                wp(20, "0.0")
                wp(30, "0.0")
                wp(70, 1 if is_closed else 0)
                for pt in pts:
                    wp(0, "VERTEX")
                    wp(8, safe_play)
                    wp(62, p_aci)
                    wp(10, f"{pt[0]:.4f}")
                    wp(20, f"{pt[1]:.4f}")
                    wp(30, "0.0")
                wp(0, "SEQEND")
                wp(8, safe_play)

            for l_lay, l_aci, lp0, lp1 in sb.get('lines', []):
                safe_llay = format_cad_text(l_lay, for_layer_or_block=True)
                wp(0, "LINE")
                wp(8, safe_llay)
                wp(62, l_aci)
                wp(10, f"{lp0[0]:.4f}")
                wp(20, f"{lp0[1]:.4f}")
                wp(30, "0.0")
                wp(11, f"{lp1[0]:.4f}")
                wp(21, f"{lp1[1]:.4f}")
                wp(31, "0.0")

            for s_lay, s_aci, s_pts in sb.get('solids', []):
                safe_slay = format_cad_text(s_lay, for_layer_or_block=True)
                p0, p1, p2 = s_pts[0], s_pts[1], s_pts[2]
                if len(s_pts) >= 4:
                    p2, p3 = s_pts[3], s_pts[2]
                else:
                    p3 = p2
                wp(0, "SOLID")
                wp(8, safe_slay)
                wp(62, s_aci)
                wp(10, f"{p0[0]:.4f}")
                wp(20, f"{p0[1]:.4f}")
                wp(30, "0.0")
                wp(11, f"{p1[0]:.4f}")
                wp(21, f"{p1[1]:.4f}")
                wp(31, "0.0")
                wp(12, f"{p2[0]:.4f}")
                wp(22, f"{p2[1]:.4f}")
                wp(32, "0.0")
                wp(13, f"{p3[0]:.4f}")
                wp(23, f"{p3[1]:.4f}")
                wp(33, "0.0")

            for c_lay, c_aci, ccx, ccy, cr in sb.get('circles', []):
                safe_clay = format_cad_text(c_lay, for_layer_or_block=True)
                wp(0, "CIRCLE")
                wp(8, safe_clay)
                wp(62, c_aci)
                wp(10, f"{ccx:.4f}")
                wp(20, f"{ccy:.4f}")
                wp(30, "0.0")
                wp(40, f"{cr:.4f}")

            for a_lay, a_aci, acx, acy, ar, aa0, aa1 in sb.get('arcs', []):
                safe_alay = format_cad_text(a_lay, for_layer_or_block=True)
                wp(0, "ARC")
                wp(8, safe_alay)
                wp(62, a_aci)
                wp(10, f"{acx:.4f}")
                wp(20, f"{acy:.4f}")
                wp(30, "0.0")
                wp(40, f"{ar:.4f}")
                wp(50, f"{aa0:.4f}")
                wp(51, f"{aa1:.4f}")

            for t_lay, t_aci, txt, t_pos, th, tang in sb.get('texts', []):
                safe_tlay = format_cad_text(t_lay, for_layer_or_block=True)
                wp(0, "TEXT")
                wp(8, safe_tlay)
                wp(62, t_aci)
                wp(10, f"{t_pos[0]:.4f}")
                wp(20, f"{t_pos[1]:.4f}")
                wp(30, "0.0")
                wp(40, f"{th:.4f}")
                wp(41, "0.78")
                wp(1, format_cad_text(txt))
                wp(50, f"{tang:.2f}")
                wp(7, "STANDARD")

            wp(0, "ENDBLK")
            wp(8, "0")
        wp(0, "ENDSEC")

        wp(0, "SECTION")
        wp(2, "ENTITIES")

        for d in dimensions_out:
            lay = format_cad_text(d['layer'], for_layer_or_block=True)
            wp(0, "DIMENSION")
            wp(8, lay)
            wp(62, d['aci'])
            wp(2, d['block_name'])
            wp(10, f"{d['t2'][0]:.4f}")
            wp(20, f"{d['t2'][1]:.4f}")
            wp(30, "0.0")
            wp(11, f"{d['text_mid'][0]:.4f}")
            wp(21, f"{d['text_mid'][1]:.4f}")
            wp(31, "0.0")
            wp(70, 0)
            if d['text']:
                wp(1, format_cad_text(d['text']))
            wp(13, f"{d['defpoint1'][0]:.4f}")
            wp(23, f"{d['defpoint1'][1]:.4f}")
            wp(33, "0.0")
            wp(14, f"{d['defpoint2'][0]:.4f}")
            wp(24, f"{d['defpoint2'][1]:.4f}")
            wp(34, "0.0")
            wp(50, f"{d['dim_angle_deg']:.2f}")

        for sb in sym_blocks_out:
            wp(0, "INSERT")
            wp(8, format_cad_text(sb['layer'], for_layer_or_block=True))
            wp(2, sb['block_name'])
            wp(10, f"{sb['ins_pt'][0]:.4f}")
            wp(20, f"{sb['ins_pt'][1]:.4f}")
            wp(30, "0.0")

        for layer, aci, p1, p2 in lines_out:
            wp(0, "LINE")
            wp(8, format_cad_text(layer, for_layer_or_block=True))
            wp(62, aci)
            wp(10, f"{p1[0]:.4f}")
            wp(20, f"{p1[1]:.4f}")
            wp(30, "0.0")
            wp(11, f"{p2[0]:.4f}")
            wp(21, f"{p2[1]:.4f}")
            wp(31, "0.0")

        for layer, aci, cx, cy, r in circles_out:
            wp(0, "CIRCLE")
            wp(8, format_cad_text(layer, for_layer_or_block=True))
            wp(62, aci)
            wp(10, f"{cx:.4f}")
            wp(20, f"{cy:.4f}")
            wp(30, "0.0")
            wp(40, f"{r:.4f}")

        for layer, aci, cx, cy, r, a0, a1 in arcs_out:
            wp(0, "ARC")
            wp(8, format_cad_text(layer, for_layer_or_block=True))
            wp(62, aci)
            wp(10, f"{cx:.4f}")
            wp(20, f"{cy:.4f}")
            wp(30, "0.0")
            wp(40, f"{r:.4f}")
            wp(50, f"{a0:.4f}")
            wp(51, f"{a1:.4f}")

        for layer, aci, pts, is_closed in polylines_out:
            lay = format_cad_text(layer, for_layer_or_block=True)
            wp(0, "POLYLINE")
            wp(8, lay)
            wp(62, aci)
            wp(66, 1)
            wp(10, "0.0")
            wp(20, "0.0")
            wp(30, "0.0")
            wp(70, 1 if is_closed else 0)
            for pt in pts:
                wp(0, "VERTEX")
                wp(8, lay)
                wp(62, aci)
                wp(10, f"{pt[0]:.4f}")
                wp(20, f"{pt[1]:.4f}")
                wp(30, "0.0")
            wp(0, "SEQEND")
            wp(8, lay)

        for layer, aci, pts in solids_out:
            p0, p1, p2 = pts[0], pts[1], pts[2]
            if len(pts) >= 4:
                p2, p3 = pts[3], pts[2]
            else:
                p3 = p2
            wp(0, "SOLID")
            wp(8, format_cad_text(layer, for_layer_or_block=True))
            wp(62, aci)
            wp(10, f"{p0[0]:.4f}")
            wp(20, f"{p0[1]:.4f}")
            wp(30, "0.0")
            wp(11, f"{p1[0]:.4f}")
            wp(21, f"{p1[1]:.4f}")
            wp(31, "0.0")
            wp(12, f"{p2[0]:.4f}")
            wp(22, f"{p2[1]:.4f}")
            wp(32, "0.0")
            wp(13, f"{p3[0]:.4f}")
            wp(23, f"{p3[1]:.4f}")
            wp(33, "0.0")

        for layer, aci, txt, x_mm, y_mm, h_mm, angle in texts_out:
            wp(0, "TEXT")
            wp(8, format_cad_text(layer, for_layer_or_block=True))
            wp(62, aci)
            wp(10, f"{x_mm:.4f}")
            wp(20, f"{y_mm:.4f}")
            wp(30, "0.0")
            wp(40, f"{h_mm:.4f}")
            wp(41, "0.78")
            wp(1, format_cad_text(txt))
            wp(50, f"{angle:.2f}")
            wp(7, "STANDARD")

        wp(0, "ENDSEC")
        wp(0, "EOF")
